#!/usr/bin/env python3
"""Generate src/core/case_fold_data.inc from Unicode CaseFolding.txt (status C + S only).

Usage: python3 -I src/core/tools/gen_case_fold.py /usr/share/unicode/CaseFolding.txt \
           > src/core/case_fold_data.inc

The output is checked in; the build never runs this script. Mappings are compressed into
runs (first, count, stride, delta): code points first, first+stride, ... map to cp + delta.
"""
import re
import sys


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    path = sys.argv[1]
    version = None
    pairs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.match(r"#\s*CaseFolding-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            code, status, mapping = [p.strip() for p in line.split(";")[:3]]
            if status not in ("C", "S"):
                continue
            targets = mapping.split()
            assert len(targets) == 1, line
            pairs.append((int(code, 16), int(targets[0], 16)))
    if version is None:
        print("error: no CaseFolding-x.y.z.txt header line", file=sys.stderr)
        return 1
    pairs.sort()

    runs = []  # [first, count, stride, delta]
    for cp, to in pairs:
        delta = to - cp
        if runs:
            r = runs[-1]
            last = r[0] + (r[1] - 1) * r[2]
            if r[3] == delta and r[1] < 0xFFFF:
                if r[1] == 1 and cp - last in (1, 2):
                    r[2] = cp - last
                    r[1] += 1
                    continue
                if r[1] > 1 and cp - last == r[2]:
                    r[1] += 1
                    continue
        runs.append([cp, 1, 1, delta])

    out = sys.stdout
    out.write("// Generated by src/core/tools/gen_case_fold.py from CaseFolding-%s.txt\n" % version)
    out.write("// (statuses C and S, %d mappings, %d runs). Do not edit by hand.\n" %
              (len(pairs), len(runs)))
    out.write("// Included by case_fold.cpp after the definition of FoldRun.\n")
    out.write("// NOLINTBEGIN\n")
    out.write("inline constexpr std::string_view kCaseFoldingUnicodeVersion = \"%s\";\n" % version)
    out.write("inline constexpr FoldRun kFoldRuns[] = {\n")
    for first, count, stride, delta in runs:
        out.write("    {0x%05X, %d, %d, %d},\n" % (first, count, stride, delta))
    out.write("};\n")
    out.write("// NOLINTEND\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
